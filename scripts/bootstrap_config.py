#!/usr/bin/env python3
"""Rebuild terminal/backend/config.py from a private keys file.

Why this exists
---------------
`terminal/backend/config.py` holds live API keys and is gitignored, so it never
travels with the repo. On a fresh machine (new laptop, new cloud session) the
code is there but the keys are not. This script regenerates config.py in one
command from a private keys file you keep OUTSIDE the repo (or in the repo root
but gitignored).

Usage
-----
    python3 scripts/bootstrap_config.py                 # reads ./keys.local.env
    python3 scripts/bootstrap_config.py --from keys.env
    python3 scripts/bootstrap_config.py --from API_KEYS_with_values_1.md
    python3 scripts/bootstrap_config.py --check         # don't write, just report
    python3 scripts/bootstrap_config.py --force         # overwrite without prompt

Input formats (both accepted, in the same file if you like)
-----------------------------------------------------------
  1. dotenv lines:         NAME=value            (inline "# comment" is stripped)
  2. markdown table cells: `NAME` = `value`       (so you can point it straight
                                                   at API_KEYS.md)

Security
--------
- Never prints a key value. Only names and counts.
- Writes config.py with 0600 permissions.
- Refuses to write anywhere that is git-tracked (config.py must stay ignored).
- Run with `python3 -I` if the keys file sits next to untrusted downloads.

stdlib only.
"""
from __future__ import annotations
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_OUT = os.path.join(REPO, "terminal", "backend", "config.py")
DEFAULT_SOURCES = [
    os.path.join(REPO, "keys.local.env"),
    os.path.expanduser("~/.openquant/keys.env"),
]

# Only names matching this are accepted as env vars (ignores prose, headers).
NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]{2,}$")
DOTENV_RE = re.compile(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$")
BACKTICK_RE = re.compile(r"`([A-Z][A-Z0-9_]{2,})`\s*=\s*`([^`]+)`")

# Output grouping — purely cosmetic. Unknown keys are written under "additional".
GROUPS = [
    ("markets / prices / news", [
        "LSE_API_KEY", "FRED_API_KEY", "MARKETAUX_API_KEY",
        "TIINGO_API_KEY", "ALPHAVANTAGE_API_KEY", "FMP_API_KEY", "API_NINJAS_KEY",
    ]),
    ("execution (paper only)", [
        "APCA_API_KEY_ID", "APCA_API_SECRET_KEY", "APCA_API_BASE_URL",
    ]),
    ("causal sensors + data breadth", [
        "EIA_API_KEY", "FIRMS_MAP_KEY", "OPENFDA_API_KEY", "FDA_DASHBOARD_KEY",
        "CENSUS_API_KEY", "BLS_API_KEY", "LABORCURRENT_API_KEY", "DOL_API_KEY",
        "DATA_GOV_API_KEY", "NASS_API_KEY", "USDA_MARS_API_KEY",
        "FMCSA_WEBKEY", "SOCRATA_APP_TOKEN", "SEC_USER_AGENT",
    ]),
    ("satellite / environmental", [
        "CDSE_CLIENT_ID", "CDSE_CLIENT_SECRET", "EARTHDATA_TOKEN",
        "NCEI_TOKEN", "OPENAQ_API_KEY", "AISSTREAM_API_KEY",
    ]),
]


def strip_inline_comment(value: str) -> str:
    """Drop a trailing ' # ...' comment, respecting simple quoting."""
    if value[:1] in ("'", '"'):
        q = value[0]
        end = value.find(q, 1)
        if end != -1:
            return value[1:end]
    # only treat ' #' (space then hash) as a comment, so '#' inside a token stays
    cut = value.find(" #")
    if cut != -1:
        value = value[:cut]
    return value.strip().strip("'\"")


def parse(text: str) -> dict:
    found: dict[str, str] = {}
    in_fence = False
    for raw in text.splitlines():
        line = raw.rstrip("\n")
        if line.strip().startswith("```"):
            in_fence = not in_fence
            continue
        # markdown table / prose:  `NAME` = `value`
        for m in BACKTICK_RE.finditer(line):
            name, val = m.group(1), m.group(2).strip()
            if NAME_RE.match(name) and val and "…" not in val and "<" not in val:
                found.setdefault(name, val)  # first wins (fenced block is first)
        # dotenv:  NAME=value   (inside a fence, or a bare line with no backticks)
        if "`" in line:
            continue
        if line.strip().startswith("#") or not line.strip():
            continue
        m = DOTENV_RE.match(line)
        if m:
            name, val = m.group(1).upper(), strip_inline_comment(m.group(2))
            if NAME_RE.match(name) and val and "<" not in val:
                found[name] = val  # dotenv overrides a table cell of the same name
    return found


def render(keys: dict) -> str:
    lines = [
        '"""Local secrets for OpenQuant — generated by scripts/bootstrap_config.py.',
        "",
        "SECURITY: this file holds live API keys. It is gitignored. Do NOT commit,",
        "share, or expose it to a browser. Real environment variables override these",
        "(os.environ.setdefault), so a deployed host can set them without editing here.",
        "Regenerate with:  python3 scripts/bootstrap_config.py --from <your keys file>",
        '"""',
        "import os",
        "",
        "_DEFAULTS = {",
    ]
    written = set()
    for title, names in GROUPS:
        present = [n for n in names if n in keys]
        if not present:
            continue
        lines.append(f"    # {title}")
        for n in present:
            lines.append(f"    {n!r}: {keys[n]!r},")
            written.add(n)
    extra = sorted(k for k in keys if k not in written)
    if extra:
        lines.append("    # additional")
        for n in extra:
            lines.append(f"    {n!r}: {keys[n]!r},")
    lines += [
        "}",
        "for _k, _v in _DEFAULTS.items():",
        "    if _v:",
        "        os.environ.setdefault(_k, _v)",
        "",
    ]
    return "\n".join(lines)


def is_git_tracked(path: str) -> bool:
    import subprocess
    try:
        r = subprocess.run(
            ["git", "-C", REPO, "ls-files", "--error-unmatch", os.path.relpath(path, REPO)],
            capture_output=True, text=True)
        return r.returncode == 0
    except Exception:
        return False


def main() -> int:
    ap = argparse.ArgumentParser(description="Rebuild config.py from a private keys file.")
    ap.add_argument("--from", dest="src", help="keys file (dotenv or API_KEYS.md); "
                    "default: keys.local.env or ~/.openquant/keys.env")
    ap.add_argument("--out", dest="out", default=DEFAULT_OUT, help="output config.py path")
    ap.add_argument("--check", action="store_true", help="parse and report, do not write")
    ap.add_argument("--force", action="store_true", help="overwrite without prompting")
    args = ap.parse_args()

    src = args.src
    if not src:
        for cand in DEFAULT_SOURCES:
            if os.path.exists(cand):
                src = cand
                break
    if not src or not os.path.exists(src):
        print("no keys file found. Pass --from <file>, or create keys.local.env in the "
              "repo root (see RESUME.md).", file=sys.stderr)
        return 2

    with open(src, "r", encoding="utf-8") as fh:
        keys = parse(fh.read())
    if not keys:
        print(f"parsed 0 keys from {src} — wrong format? "
              "Expected NAME=value lines or `NAME` = `value` cells.", file=sys.stderr)
        return 2

    print(f"parsed {len(keys)} keys from {os.path.relpath(src)}:")
    print("  " + ", ".join(sorted(keys)))
    if args.check:
        return 0

    if is_git_tracked(args.out):
        print(f"refusing to write {args.out}: it is git-tracked and must stay "
              "gitignored.", file=sys.stderr)
        return 3
    if os.path.exists(args.out) and not args.force:
        ans = input(f"{os.path.relpath(args.out)} exists. Overwrite? [y/N] ").strip().lower()
        if ans not in ("y", "yes"):
            print("aborted.")
            return 1

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    body = render(keys)
    fd = os.open(args.out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.chmod(args.out, 0o600)
    print(f"wrote {os.path.relpath(args.out)} ({len(keys)} keys, mode 0600).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
